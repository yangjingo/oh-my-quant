async (page) => {
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  await page.setViewportSize({width: 1440, height: 600});
  await page.goto('http://127.0.0.1:4176/');
  await page.getByRole('heading', {name: /示例结论/}).waitFor();
  const input = page.getByRole('combobox', {name: '研究问题'});
  await input.fill('待保留的研究草稿');
  const before = await page.locator('#stream').evaluate(el => { el.scrollTop = 70; return el.scrollTop; });
  await page.getByRole('button', {name: '展开概览'}).focus();
  await page.keyboard.press('Enter');
  await page.getByRole('button', {name: '返回对话'}).waitFor();
  check(await page.getByRole('button', {name: '返回对话'}).evaluate(el => document.activeElement === el), 'keyboard focus lost on expand');
  check(!(await input.isVisible()), 'conversation input should not cover the expanded Overview');
  await page.locator('#projectSwitch').click();
  await page.locator('.session-select').filter({hasText:'结构跟踪'}).click();
  await page.locator('.session-select').filter({hasText:'回撤结构研究'}).click();
  await page.waitForFunction(() => document.querySelector('#sessionTitle')?.textContent?.includes('回撤结构研究'));
  await page.waitForFunction(() => document.activeElement?.textContent === '返回对话');
  await page.screenshot({path:'output/web-react/overview-expanded-wide.png'});
  await page.setViewportSize({width:390,height:480});
  check(await page.getByRole('button', {name:'返回对话'}).isVisible(), 'resize closed expanded overview');
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'narrow overflow');
  await page.screenshot({path:'output/web-react/overview-expanded-narrow.png'});
  await page.getByRole('button', {name:'返回对话'}).click();
  check(await input.inputValue() === '待保留的研究草稿', 'draft was lost');
  check(await input.isVisible(), 'conversation remains obscured');
  check(!(await page.locator('#overview').isVisible()), 'narrow overlay remains over conversation');
  const after = await page.locator('#stream').evaluate(el => el.scrollTop);
  check(Math.abs(after - before) <= 2, `conversation scroll lost: ${before} -> ${after}`);
  await page.getByRole('button', {name:'切换研究概览'}).click();
  const overview = page.locator('#overview');
  const marketScroll = await overview.evaluate(el => { el.scrollTop = 100; return el.scrollTop; });
  const marketSize = await overview.evaluate(el => [el.scrollHeight, el.clientHeight]);
  const expandBox = await page.getByRole('button', {name:'展开概览'}).boundingBox();
  await page.mouse.click(expandBox.x + expandBox.width / 2, expandBox.y + expandBox.height / 2);
  await page.getByRole('button', {name:'返回对话'}).click();
  await page.getByRole('button', {name:'切换研究概览'}).click();
  const marketAfter = await overview.evaluate(el => el.scrollTop);
  check(Math.abs(marketAfter - marketScroll) <= 2, `Overview scroll lost: ${marketScroll} -> ${marketAfter}, before ${marketSize}, after ${await overview.evaluate(el => [el.scrollHeight, el.clientHeight])}`);
  console.log('Overview expansion: keyboard, resize, draft and both scroll positions passed');
}
