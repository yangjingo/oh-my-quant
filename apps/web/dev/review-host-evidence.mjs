import { spawn } from 'node:child_process';
import { join } from 'node:path';
import { writeFile } from 'node:fs/promises';
import { advanceFixture } from './review-host-control.mjs';

export async function captureHost({ browser, output, root }) {
  const child = spawn('bun', ['run', 'tests/app/dev/review-host-fixture.ts'], { cwd: root, stdio: ['ignore', 'pipe', 'pipe'] });
  let logs = ''; child.stderr.on('data', data => { logs += data; });
  const closed = new Promise(done => child.once('close', done));
  let context;
  const results = [];
  let delayedToolGateObservations = 0;
  try {
    const fixture = await new Promise((done, reject) => {
      let text = ''; const timer = setTimeout(() => reject(new Error('Fixture startup timeout: ' + logs)), 30000);
      child.once('error', error => { clearTimeout(timer); reject(error); });
      child.stdout.on('data', data => { text += data; const line = text.split('\n').find(line => line.startsWith('{"origin"'));
        if (line) { clearTimeout(timer); done(JSON.parse(line)); } });
    });
    context = await browser.newContext({ viewport: { width: 1280, height: 720 }, recordVideo: { dir: join(output, 'host-video'), size: { width: 1280, height: 720 } } });
    const page = await context.newPage(), errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const capture = async name => {
      if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error(name + ': page overflow');
      await page.screenshot({ path: join(output, name + '.png'), scale: 'css' }); results.push(name);
    };
    const next = async () => { delayedToolGateObservations += await advanceFixture(fixture.control); };
    const state = async label => page.locator('.agent-status-label').last().filter({ hasText: new RegExp('^' + label + '$') }).waitFor();
    await page.goto(fixture.origin); const input = page.getByRole('combobox', { name: '研究问题', exact: true }); await input.waitFor();
    await page.getByRole('button', { name: '刷新行情', exact: true }).waitFor();
    await page.locator('#overview [role="status"]').filter({ hasText: '5/5 可用' }).waitFor();
    await page.locator('#overview').getByText(/相对前收涨跌/).first().waitFor();
    await page.locator('#overview').getByText(/15:00:03/).first().waitFor();
    await capture('host-market-01-dated-values');
    await page.locator('#overview .auto-refresh').filter({ hasText: '约 5 秒' }).waitFor();
    const initialMarketTime = await page.locator('#overview .refresh > span').first().textContent();
    await page.waitForFunction(previous => { const stamp = document.querySelector('#overview .refresh > span'); return !!stamp && stamp.textContent !== previous; }, initialMarketTime);
    await page.locator('#overview [role="status"]').filter({ hasText: '5/5 可用' }).waitFor();
    if ((await (await fetch(fixture.control + '/state')).json()).requests !== 0) throw new Error('Automatic market update invoked a model');
    await capture('host-market-auto-updated');
    await fetch(fixture.control + '/market', { method: 'POST' });
    await page.getByRole('button', { name: '刷新行情', exact: true }).click();
    await page.locator('#overview [role="status"]').filter({ hasText: '正在刷新' }).waitFor();
    await page.locator('#overview').getByText(/刷新中 · 旧值/).first().waitFor();
    await capture('host-market-02-retained-refresh');
    await page.getByRole('button', { name: '重试失败项', exact: true }).waitFor();
    await capture('host-market-03-partial-stale');
    await fetch(fixture.control + '/market', { method: 'POST' });
    await page.getByRole('button', { name: '重试失败项', exact: true }).click();
    await page.locator('#overview [role="status"]').filter({ hasText: '5/5 可用' }).waitFor();
    await capture('host-market-04-retry-restored');
    const submit = async text => {
      const before = (await (await fetch(fixture.control + '/state')).json()).requests;
      await input.fill(text); await input.press('Enter'); await state('等待模型响应');
      for (let i = 0; i < 150; i++) {
        const actual = await (await fetch(fixture.control + '/state')).json();
        if (actual.requests > before && actual.stage === 'waiting' && actual.canAdvance) return;
        await new Promise(done => setTimeout(done, 100));
      }
      throw new Error('New controlled provider request did not reach waiting');
    };
    await page.getByRole('heading', { name: '开始一份研究' }).waitFor(); await capture('host-01-empty');
    await submit('Compare supplied scenarios'); await capture('host-02-waiting');
    await page.reload(); await page.getByRole('button', { name: '停止生成', exact: true }).waitFor();
    if ((await (await fetch(fixture.control + '/state')).json()).requests !== 1) throw new Error('Reload replayed the request');
    if (!(await page.locator('#sessionTitle').innerText()).includes('Compare supplied scenarios')) throw new Error('Auto-name missing');
    await capture('host-03-reloaded-waiting');
    await page.getByRole('button', { name: 'review-fixture', exact: true }).click();
    const model = page.getByRole('textbox', { name: '模型 ID', exact: true }); await model.fill('busy-model'); await page.getByRole('button', { name: '保存偏好', exact: true }).click();
    await page.locator('.error-feedback').waitFor(); await capture('host-04-busy-model-rejected'); await page.getByRole('button', { name: '关闭窗口', exact: true }).click();
    await next(); await state('思考中'); await capture('host-05-thinking');
    await next(); await state('准备调用工具'); await capture('host-06-preparing');
    await next(); await state('正在调用工具'); await capture('host-07-executing');
    await next(); await state('正在生成回答'); await capture('host-08-answering');
    await next(); await page.getByRole('button', { name: '发送问题', exact: true }).waitFor();
    const ended = await page.locator('.turn-assistant').last().innerText();
    await page.waitForTimeout(1100); if (await page.locator('.turn-assistant').last().innerText() !== ended) throw new Error('Terminal timer advanced');
    await capture('host-09-result');
    const modelCallsBeforeEvidence = (await (await fetch(fixture.control + '/state')).json()).requests;
    await page.locator('.tool-history').last().locator('summary').first().click();
    await page.locator('.tool-record').last().locator('summary').first().click();
    await page.locator('.tool-record').last().getByText('查看工具返回内容', { exact: true }).click();
    await page.locator('.tool-record .tool-result pre').last().filter({ hasText: '100' }).waitFor();
    await capture('host-tool-result-expanded');
    await page.getByRole('button', { name: '查看本会话研究证据', exact: true }).last().click();
    await page.getByRole('tab', { name: /证据/ }).waitFor();
    await page.locator('.research-content').getByText('查看工具返回内容', { exact: true }).click();
    await page.locator('.research-content .tool-result pre').filter({ hasText: '100' }).waitFor();
    await capture('host-evidence-tool-result');
    await page.setViewportSize({ width: 390, height: 480 });
    await capture('host-evidence-tool-result-narrow');
    if ((await (await fetch(fixture.control + '/state')).json()).requests !== modelCallsBeforeEvidence) throw new Error('Inspecting evidence invoked model');
    await page.getByRole('button', { name: '关闭窗口', exact: true }).click();
    await page.setViewportSize({ width: 1280, height: 720 });

    const table = page.locator('.turn-assistant').last().getByRole('region', { name: '数据表格', exact: true });
    await table.waitFor();
    const expectedRows = [['A', '2026-10-23', '0.00', 'CNY', '—', '同一窗口'], ['B', '2026-10-22', '80.00', 'USD', '—', '跨窗口，不直接比较']];
    const actualRows = await table.locator('tbody tr').evaluateAll(rows => rows.map(row => [...row.querySelectorAll('td')].map(cell => cell.textContent)));
    if (JSON.stringify(actualRows) !== JSON.stringify(expectedRows)) throw new Error('Research table changed associations, units, dates or missing values');
    await page.setViewportSize({ width: 390, height: 480 });
    await table.scrollIntoViewIfNeeded(); await table.focus(); await table.press('ArrowRight');
    await page.waitForFunction(() => { const el = [...document.querySelectorAll('.table-scroll')].at(-1); return el && document.activeElement === el && el.scrollLeft > 0 && el.scrollWidth > el.clientWidth; });
    await capture('host-table-narrow-keyboard-scroll');
    await page.setViewportSize({ width: 1280, height: 720 });
    await submit('Follow up on those supplied scenarios');
    await input.fill('Retained draft'); await input.press('Enter'); await capture('host-10-follow-up-draft');
    await page.getByRole('button', { name: '停止生成', exact: true }).click(); await state('已停止');
    if (await input.inputValue() !== 'Retained draft') throw new Error('Stop lost draft'); await capture('host-11-stopped');
    await page.getByRole('button', { name: 'review-fixture', exact: true }).click(); await model.fill('review-fixture-next'); await page.getByRole('button', { name: '保存偏好', exact: true }).click();
    await page.locator('.operation-feedback:not(.error-feedback)').waitFor(); await capture('host-12-model-saved'); await page.getByRole('button', { name: '关闭窗口', exact: true }).click();
    const beforeReference = (await (await fetch(fixture.control + '/state')).json()).requests;
    await input.fill('Summarize @file:evidence.md'); await input.press('Enter');
    await page.getByRole('alert').filter({ hasText: '引用' }).waitFor();
    if (await input.inputValue() !== 'Summarize @file:evidence.md') throw new Error('Rejected reference lost draft');
    if ((await (await fetch(fixture.control + '/state')).json()).requests !== beforeReference) throw new Error('Unavailable reference called provider');
    await capture('host-reference-unavailable');
    await submit('FAIL supplied fixture'); await next(); await state('思考中'); await next(); await state('准备调用工具'); await next(); await state('正在调用工具'); await next(); await state('正在生成回答');
    await page.locator('.tool-record[data-state="failed"]').waitFor(); await capture('host-13-tool-failed'); await next(); await page.getByRole('button', { name: '发送问题', exact: true }).waitFor();
    await submit('Stop before dispatch'); await next(); await state('思考中'); await next(); await state('准备调用工具');
    await page.getByRole('button', { name: '停止生成', exact: true }).click(); await state('已停止');
    await page.locator('.tool-history').last().locator('summary').first().click(); await page.locator('.tool-record[data-state="not-run"]').waitFor(); await capture('host-14-not-executed');
    await page.setViewportSize({ width: 390, height: 844 }); await capture('host-15-narrow');
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await submit('Reduced motion fixture');
    if (await page.locator('.agent-status-mark').last().evaluate(element => getComputedStyle(element).animationName) !== 'none') throw new Error('Reduced motion animates');
    await capture('host-16-reduced-motion'); await page.getByRole('button', { name: '停止生成', exact: true }).click(); await state('已停止');
    await page.setViewportSize({ width: 1280, height: 720 });
    await submit('LEGACY synthetic reading exhibit'); await next(); await state('思考中'); await next(); await state('准备调用工具'); await next(); await state('正在调用工具'); await next(); await state('正在生成回答'); await next();
    await page.getByRole('button', { name: '发送问题', exact: true }).waitFor();
    const legacyAnswer = page.locator('.turn-assistant').last().locator('.legacy-answer');
    await legacyAnswer.waitFor();
    const expectedLegacy = '以下为合成展示，不是投资结论。\n\n\n观察摘要\n────────────────────────\n假设 A    2026-10-23    0.00 CNY    —\n假设 B    2026-10-22    80.00 USD   跨窗口，不能直接比较\n\n\n复核边界\n────────────────────────\n原始数据尚未独立复核，不代表实际行情。';
    if (await legacyAnswer.textContent() !== expectedLegacy) throw new Error('Legacy decorations changed original text');
    if (await page.locator('.turn-assistant').last().locator('.thinking-preview').count()) throw new Error('Settled thinking still exposes a long preview');
    await legacyAnswer.scrollIntoViewIfNeeded(); await capture('host-reading-wide');
    await page.setViewportSize({ width: 390, height: 480 }); await legacyAnswer.scrollIntoViewIfNeeded(); await capture('host-reading-narrow');
    if (errors.length) throw new Error(errors.join('\n'));
    return { result: 'passed', captures: results, data: 'controlled fake provider / actual core and calculator', delayedToolGateObservations, errors };
  } finally {
    await context?.close(); if (child.exitCode === null) child.kill('SIGTERM'); await closed;
    await writeFile(join(output, 'host-fixture-log.txt'), logs);
  }
}
